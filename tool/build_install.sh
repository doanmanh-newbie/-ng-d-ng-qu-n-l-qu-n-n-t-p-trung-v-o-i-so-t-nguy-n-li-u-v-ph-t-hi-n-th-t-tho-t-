#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DB="$ROOT/database"
INSTALL="$DB/install"

# The four grouped SQL files are the only editable source of truth.
modules=(
  01_foundation.sql
  02_operations_reconciliation.sql
  03_read_apis.sql
  04_membership_sessions.sql
)

mkdir -p "$INSTALL"

# Remove obsolete generated bundles from the former 7-file layout.
rm -f "$INSTALL/01_schema.sql" \
  "$INSTALL/02_security.sql" \
  "$INSTALL/03_operations.sql" \
  "$INSTALL/04_reconciliation_reports.sql" \
  "$INSTALL/05_membership_invites.sql" \
  "$INSTALL/06_app_read_api.sql" \
  "$INSTALL/07_owner_dashboard.sql"

for source in "${modules[@]}"; do
  output="$INSTALL/$source"
  {
    printf '%s\n' \
      "-- Fore generated install module: $source" \
      '-- Generated by tool/build_install.sh; edit database/0[1-4]_*.sql only.' \
      '-- Apply modules in numeric order after database/00_reset_schema.sql if rebuilding.' \
      ''
    cat "$DB/$source"
  } > "$output"
done

{
  printf '%s\n' \
    '-- Fore generated test rebuild. DESTRUCTIVE: TEST DATABASE ONLY.' \
    '-- Generated by tool/build_install.sh; do not run on a database with real data.'
  for source in 00_reset_schema.sql "${modules[@]}"; do
    printf '\n-- >>> SOURCE: database/%s\n' "$source"
    cat "$DB/$source"
  done
} > "$DB/dev/rebuild_test_database.sql"

perl -0pi -e 's/(?:\r?\n)+\z/\n/' "$DB/dev/rebuild_test_database.sql"

echo 'Generated the four install modules and database/dev/rebuild_test_database.sql.'
